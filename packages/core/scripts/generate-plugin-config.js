#!/usr/bin/env node

/**
 * Reads packages/plugins.json and generates:
 * 1. Vite alias paths (relative from core/ to plugin src/)
 * 2. TypeScript path entries
 *
 * Usage: node packages/core/scripts/generate-plugin-config.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const PLUGINS_JSON = path.join(ROOT, 'plugins.json');
const CORE_DIR = path.resolve(__dirname, '..');
const VITE_CONFIG = path.join(CORE_DIR, 'vite.config.ts');
const TSCONFIG = path.join(CORE_DIR, 'tsconfig.json');

// Read plugins.json
const plugins = JSON.parse(fs.readFileSync(PLUGINS_JSON, 'utf-8'));

// --- Generate Vite alias paths (relative from core/ directory) ---
const aliasEntries = plugins.map(p => {
  // entry is like "../plugin-pdf/src" — already relative to core/
  return `  '${p.package}': '${p.entry}',`;
});

const viteAliasContent = `// AUTO-GENERATED by generate-plugin-config.js — DO NOT EDIT
// Source: packages/plugins.json
// These are relative paths from packages/core/ to each plugin's src/ directory.

export const pluginAliasPaths: Record<string, string> = {
${aliasEntries.join('\n')}
};
`;

fs.writeFileSync(path.join(CORE_DIR, 'src', 'generated-plugin-aliases.ts'), viteAliasContent);
console.log('Generated src/generated-plugin-aliases.ts');

// --- Update tsconfig.json paths ---
const tsconfig = JSON.parse(fs.readFileSync(TSCONFIG, 'utf-8'));

// Keep existing non-plugin paths, add plugin paths
const pluginPaths = {};
for (const p of plugins) {
  const packageName = p.package;
  // Resolve entry relative to core dir
  const entryAbs = path.resolve(CORE_DIR, p.entry);
  const entryRel = path.relative(CORE_DIR, entryAbs).replace(/\\/g, '/');
  pluginPaths[packageName] = [entryRel];
}

tsconfig.compilerOptions.paths = {
  '@/*': ['src/*'],
  '@mdview/plugin-api': ['../plugin-api/src'],
  ...pluginPaths,
};

fs.writeFileSync(TSCONFIG, JSON.stringify(tsconfig, null, 2) + '\n');
console.log('Updated tsconfig.json');
console.log(`Done — ${plugins.length} plugin(s) configured.`);
