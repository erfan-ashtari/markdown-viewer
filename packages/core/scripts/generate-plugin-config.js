#!/usr/bin/env node
var fs = require('fs');
var path = require('path');
var ROOT = path.resolve(__dirname, '../../..');
var PD = path.join(ROOT, 'packages');
var PJ = path.join(ROOT, 'packages', 'plugins.json');
var CD = path.resolve(__dirname, '..');
var TC = path.join(CD, 'tsconfig.json');
var dirs = fs.readdirSync(PD, { withFileTypes: true }).filter(function(d) { return d.isDirectory(); }).map(function(d) { return path.join(PD, d.name); });
var plugins = [];
for (var i = 0; i < dirs.length; i++) {
  var dir = dirs[i];
  var pp = path.join(dir, 'package.json');
  if (!fs.existsSync(pp)) continue;
  var pkg;
  try { pkg = JSON.parse(fs.readFileSync(pp, 'utf-8')); } catch(e) { continue; }
  if (!pkg.contributes || !pkg.main) continue;
  plugins.push({
    name: (pkg.contributes && pkg.contributes.name) || pkg.name.replace('@mdview/', '').replace(/^plugin-/, ''),
    package: pkg.name,
    entry: path.relative(CD, path.join(dir, pkg.main)).replace(/\\/g, '/'),
    version: pkg.version,
    description: pkg.description || '',
    displayName: pkg.displayName || pkg.name,
    activationEvents: pkg.activationEvents || ['onStartup'],
    contributes: pkg.contributes,
    _mtime: fs.statSync(dir).mtimeMs
  });
}
plugins.sort(function(a, b) { return b._mtime - a._mtime; });
plugins.forEach(function(p) { delete p._mtime; });
fs.writeFileSync(PJ, JSON.stringify(plugins, null, 2));
console.log('Generated plugins.json (' + plugins.length + ' plugin(s))');
var ae = plugins.map(function(p) { return "  '" + p.package + "': '" + p.entry + "',"; });
fs.writeFileSync(path.join(CD, 'src', 'generated-plugin-aliases.ts'), '// AUTO-GENERATED by generate-plugin-config.js - DO NOT EDIT\nexport const pluginAliasPaths: Record<string, string> = {\n' + ae.join('\n') + '\n};\n');
console.log('Generated src/generated-plugin-aliases.ts');
var tc = JSON.parse(fs.readFileSync(TC, 'utf-8'));
var pp2 = {};
for (var j = 0; j < plugins.length; j++) {
  var ea = path.resolve(CD, plugins[j].entry);
  var er = path.relative(CD, ea).replace(/\\/g, '/');
  pp2[plugins[j].package] = [er];
}
tc.compilerOptions.paths = Object.assign({ '@/*': ['src/*'], '@mdview/plugin-api': ['../plugin-api/src'] }, pp2);
fs.writeFileSync(TC, JSON.stringify(tc, null, 2) + '\n');
console.log('Updated tsconfig.json');
console.log('Done - ' + plugins.length + ' plugin(s) configured.');